#!/usr/bin/env bash
# Generates compact.toml (DP-2 bar) from config.toml: points monitor-ddc.sh at the small bar's connector (output lines of i3/bars.conf.tmpl), drops disk_space, disk_iostats, the usage block and the net $ip;
# a block merged into a group whose rest is dropped loses merge_with_next.
# Usage: gen-compact.sh [out]   (default: ../compact.toml; "-" for stdout). test.sh checks it is in sync.
d=$(cd "$(dirname "$0")/.." && pwd); out=${1:-$d/compact.toml}
gen() {
  echo "# GENERATED by scripts/gen-compact.sh from config.toml - do not edit, edit config.toml and rerun."
  read -r mo so < <(awk '$1 == "output" { printf "%s ", $2 } END { print "" }' "$d/i3/bars.conf.tmpl")
  awk -v mo="$mo" -v so="$so" '
    # a kept block whose group ends on a dropped block loses its merge flag (memory on DP-2)
    function flush() {
      if (buf == "") return
      if (!drop) { printf "%s", prev; prev = buf } else if (!merged) sub(/\nmerge_with_next = true\n/, "\n", prev)
      buf = ""; drop = 0; merged = 0 }
    /^\[\[block\]\]$/ { flush() }
    /^block = "(disk_space|disk_iostats)"/ || /^command = .*claude-usage\.sh"/ { drop = 1 }
    /^merge_with_next = true$/ { merged = 1 }
    /^format = .*\$ip/ { sub(/ \$ip /, " ") }
    /^(command|cmd) = / { gsub("monitor-ddc.sh " mo, "monitor-ddc.sh " so) }
    { buf = buf $0 "\n" }
    END { flush(); printf "%s", prev }' "$d/config.toml"
}
if [ "$out" = - ]; then gen; else gen >"$out"; fi
