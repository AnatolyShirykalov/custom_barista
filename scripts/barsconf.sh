#!/usr/bin/env bash
# Prints the i3 bars.conf for a bar state (rs|off) from i3/bars.conf.tmpl.
# Used by install.sh and barcycle.sh. Paths (CONFDIR) come from the env file install.sh writes;
# BARS_ENV overrides its location. The tray is always on bar-main (DP-0; primary HDMI-0 is disconnected).
set -euo pipefail
d=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=/dev/null
. "${BARS_ENV:-${XDG_CONFIG_HOME:-$HOME/.config}/custom_barista/bars.env}"
rsfont='font pango:PragmataPro Mono, Symbols Nerd Font Mono 18'
st=${1:-}; [ "$st" = barista ] && st=rs  # migration: the removed Go bar's saved state
mc="i3status-rs $CONFDIR/config.toml"; sc="i3status-rs $CONFDIR/compact.toml"; f=$rsfont
# T1 hover: wrap the status commands in the tap wrapper (outputs read from the template); HOVER=0 or no python3 = plain
if [ "${HOVER:-1}" != 0 ] && command -v python3 >/dev/null; then
  read -r mo so < <(awk '$1 == "output" { printf "%s ", $2 } END { print "" }' "$d/../i3/bars.conf.tmpl")
  mc="$d/hover-tee.py --output $mo -- $mc"; sc="$d/hover-tee.py --output $so -- $sc"
fi
case $st in
  rs)  m=dock ;;
  off) m=invisible ;;
  *) echo "usage: $0 rs|off" >&2; exit 2 ;;
esac
echo "# state: $st (generated by barsconf.sh, rewritten by Win+i; edit i3/bars.conf.tmpl instead)"
sed -e "s|@MODE@|$m|g" -e "s|@FONT@|$f|g" -e "s|@MAIN_CMD@|$mc|g" -e "s|@SMALL_CMD@|$sc|g" "$d/../i3/bars.conf.tmpl"
