#!/usr/bin/env bash
# Applies the current setup for the user running it: pulls the repo,
# generates i3status-rs configs into ~/.config/custom_barista/, writes the bar blocks to bars.conf next to
# the i3 config (scripts/barsconf.sh, keeps the current Win+i state) and the include line plus the
# $mod+i binding between "# BEGIN/END custom_barista" markers of the i3 config.
# Usage: install.sh [--dry-run] [--no-restart] [--yes (answer the y/N questions with y)]    Safe to rerun.
set -euo pipefail

REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
dry=0; restart=1; yes=0
for a in "$@"; do
  case $a in
    --dry-run) dry=1 ;;
    --no-restart) restart=0 ;;
    --yes) yes=1 ;;
    *) echo "usage: $0 [--dry-run] [--no-restart] [--yes]" >&2; exit 2 ;;
  esac
done
say() { printf '%s\n' "$*"; }
warn() { printf 'WARN: %s\n' "$*" >&2; }
do_() { if [ $dry = 1 ]; then say "[dry-run] $*"; else "$@"; fi; }
ask() { # y/N, default no; no tty = no
  [ $dry = 1 ] && { say "[dry-run] would ask: $1 [y/N]"; return 1; }
  [ $yes = 1 ] && return 0
  [ -t 0 ] || return 1
  read -r -p "$1 [y/N] " ans; [[ $ans == [yY]* ]]
}

# 1. update
if [ -d "$REPO/.git" ]; then
  if [ -n "$(git -C "$REPO" status --porcelain)" ]; then warn "repo has local changes, skipping git pull"
  else do_ git -C "$REPO" pull --ff-only || warn "git pull failed, continuing with the current checkout"; fi
fi

# 2. dependencies
command -v i3status-rs >/dev/null || warn "missing: i3status-rs (required for the bars)"
for c in jq xclip node npx nvidia-smi xdotool pavucontrol; do
  command -v "$c" >/dev/null || warn "missing: $c (used by bar blocks/click actions)"
done
command -v yad >/dev/null || warn "missing: yad (optional, calendar/clipboard popups)"
for s in clipboard_menu.sh open_calender.sh; do
  [ -e "$HOME/scripts/$s" ] || warn "missing ~/scripts/$s (click action of a bar block; not part of this repo, copy it from the original user)"
done

# 3. i3status-rs configs: tracked files refer to ~/projects/custom_barista, generate copies with this checkout
CONFDIR=${XDG_CONFIG_HOME:-$HOME/.config}/custom_barista
do_ mkdir -p "$CONFDIR"
for f in config.toml compact.toml; do
  if [ $dry = 1 ]; then say "[dry-run] generate $CONFDIR/$f (~/projects/custom_barista -> $REPO)"
  else c=$(<"$REPO/$f"); printf '%s\n' "${c//'~/projects/custom_barista'/$REPO}" >"$CONFDIR/$f"; fi
done

# 4. i3 config
cfg=
for c in "$HOME/.i3/config" "${XDG_CONFIG_HOME:-$HOME/.config}/i3/config"; do [ -f "$c" ] && { cfg=$c; break; }; done
[ -n "$cfg" ] || { warn "no i3 config found (~/.i3/config or ~/.config/i3/config), done without i3 changes"; exit 0; }
mod='$mod'; grep -q '^[[:space:]]*set[[:space:]]\+\$mod[[:space:]]' "$cfg" || { mod=Mod4; warn "no 'set \$mod' in $cfg, using Mod4"; }
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
b=$tmp/block; w=$tmp/work
# bars live in bars.conf next to the config (rewritten by barcycle.sh on Win+i); the env file gives the
# generator and barcycle.sh the paths of this install
barsconf=$(dirname "$cfg")/bars.conf
{ printf '%s=%q\n' CONFDIR "$CONFDIR" BARSCONF "$barsconf" I3CFG "$cfg"; } >"$tmp/bars.env"
state=$( { sed -n 's/^# state: \([a-z]*\).*/\1/p' "$barsconf" 2>/dev/null || true; } | head -1); [ -n "$state" ] || state=rs  # a saved "barista" state is migrated to rs by barsconf.sh
BARS_ENV=$tmp/bars.env "$REPO/scripts/barsconf.sh" "$state" >"$tmp/bars.conf"
{ echo "# BEGIN custom_barista (generated by install.sh; bar blocks in bars.conf from i3/bars.conf.tmpl)"
  echo "include $barsconf"
  echo "bindsym $mod+i exec --no-startup-id $REPO/scripts/barcycle.sh"
  echo "# END custom_barista"; } >"$b"

# the config without our block; old top-level bar {} blocks listed from it
awk '/^# BEGIN custom_barista/{skip=1} !skip{print} /^# END custom_barista/{skip=0}' "$cfg" >"$w"
awk '{ if (!d && $0 ~ /^[ \t]*bar[ \t]*\{/) {inb=1; start=NR}
       if (inb) { l=$0; if (l !~ /^[ \t]*#/) { n=gsub(/\{/,"{",l); m=gsub(/\}/,"}",l); d+=n-m } print NR": "$0; if (d==0) inb=0 } }' "$w" >"$tmp/oldbars"
# (the awk above prints each old bar line with its number; d is reset by reaching 0)
remove_old=0
if [ -s "$tmp/oldbars" ]; then
  say "Existing bar {} blocks outside the custom_barista markers:"; sed 's/^/    /' "$tmp/oldbars"
  ask "Remove them (a backup is made)?" && remove_old=1 || warn "old bar blocks kept; they will show next to the new ones"
fi
if [ $remove_old = 1 ]; then
  awk '{ if (!d && $0 ~ /^[ \t]*bar[ \t]*\{/) inb=1
         if (inb) { l=$0; if (l !~ /^[ \t]*#/) { n=gsub(/\{/,"{",l); m=gsub(/\}/,"}",l); d+=n-m } if (d==0) inb=0; next } print }' "$w" >"$w.2" && mv "$w.2" "$w"
fi
# an old $mod+i binding would clash with ours
mi=$(grep -n "^[[:space:]]*bindsym[[:space:]]\+\(\$mod\|Mod4\)+i[[:space:]]" "$w" || true)
if [ -n "$mi" ]; then
  say "Existing \$mod+i binding:"; say "$mi" | sed 's/^/    /'
  if grep -q barcycle <<<"$mi" || ask "Comment it out (replaced by the barcycle binding)?"; then sed -i 's/^\([[:space:]]*bindsym[[:space:]]\+\(\$mod\|Mod4\)+i[[:space:]]\)/#\1/' "$w"
  else warn "kept: i3 will reject the duplicate \$mod+i binding"; fi
fi
# our block goes where the old one was, else at the end
if grep -q '^# BEGIN custom_barista' "$cfg"; then
  awk -v bf="$b" '/^# BEGIN custom_barista/{while((getline l < bf)>0) print l; skip=1} !skip{print} /^# END custom_barista/{skip=0}' "$cfg" >"$tmp/new"
  if [ $remove_old = 1 ] || [ -n "$mi" ]; then
    # old-block position is lost after the cleanup, put the block at the end
    cat "$w" "$b" >"$tmp/new"
  fi
else cat "$w" "$b" >"$tmp/new"; fi

if [ $dry = 1 ]; then
  if cmp -s "$cfg" "$tmp/new"; then say "[dry-run] i3 config $cfg unchanged"
  else say "[dry-run] i3 config $cfg would change:"; diff -u "$cfg" "$tmp/new" | sed 's/^/    /' || true; fi
  if [ -f "$barsconf" ] && cmp -s "$barsconf" "$tmp/bars.conf"; then say "[dry-run] $barsconf (state $state) unchanged"
  else say "[dry-run] $barsconf (state $state) would change:"; { if [ -f "$barsconf" ]; then diff -u "$barsconf" "$tmp/bars.conf"; else diff -u /dev/null "$tmp/bars.conf"; fi; } | sed 's/^/    /' || true; fi
  cmp -s "$CONFDIR/bars.env" "$tmp/bars.env" || say "[dry-run] write $CONFDIR/bars.env"
  exit 0
fi
cp "$tmp/bars.env" "$CONFDIR/bars.env"
changed=0; stamp=$(date +%F-%H%M)
if cmp -s "$barsconf" "$tmp/bars.conf"; then say "bars.conf already up to date"; else
  [ -f "$barsconf" ] && cp -p "$barsconf" "$barsconf.bak-$stamp"
  cp "$tmp/bars.conf" "$barsconf"; changed=1; say "bars.conf written (state $state)"
fi
if cmp -s "$cfg" "$tmp/new"; then say "i3 config already up to date"; else
  bak=$cfg.bak-$stamp; cp -p "$cfg" "$bak"; cp "$tmp/new" "$cfg"; changed=1; say "i3 config updated, backup: $bak"
fi
if [ $changed = 1 ] && command -v i3 >/dev/null && ! i3 -C -c "$cfg" >"$tmp/val" 2>&1; then
  cat "$tmp/val" >&2
  [ -n "${bak:-}" ] && cp -p "$bak" "$cfg"
  if [ -f "$barsconf.bak-$stamp" ]; then cp -p "$barsconf.bak-$stamp" "$barsconf"; else rm -f "$barsconf"; fi
  echo "i3 config validation failed, restored the previous config/bars.conf" >&2; exit 1
fi
if [ $restart = 1 ] && command -v i3-msg >/dev/null && i3-msg -t get_version >/dev/null 2>&1; then i3-msg restart >/dev/null && say "i3 restarted"; fi
say "done"
