#!/usr/bin/env bash
# Prints the i3 bars.conf for a bar state (barista|rs|off) from i3status-rust/i3/bars.conf.tmpl.
# Used by install.sh and barcycle.sh. Paths (BIN, CONFDIR) come from the env file install.sh writes;
# BARS_ENV overrides its location. The tray goes to DP-0 (primary HDMI-0 is disconnected).
set -euo pipefail
d=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=/dev/null
. "${BARS_ENV:-${XDG_CONFIG_HOME:-$HOME/.config}/custom_barista/bars.env}"
tray=DP-0
case ${1:-} in
  barista) bm=dock;      bt=$tray; rm=invisible; rt=none ;;
  rs)      bm=invisible; bt=none;  rm=dock;      rt=$tray ;;
  off)     bm=invisible; bt=none;  rm=invisible; rt=none ;;
  *) echo "usage: $0 barista|rs|off" >&2; exit 2 ;;
esac
echo "# state: $1 (generated by barsconf.sh, rewritten by Win+i; edit i3status-rust/i3/bars.conf.tmpl instead)"
sed -e "s|@BIN@|$BIN|g" -e "s|@CONFDIR@|$CONFDIR|g" -e "s|@BARISTA_MODE@|$bm|g" -e "s|@BARISTA_TRAY@|$bt|g" \
    -e "s|@RS_MODE@|$rm|g" -e "s|@RS_TRAY@|$rt|g" "$d/../i3/bars.conf.tmpl"
