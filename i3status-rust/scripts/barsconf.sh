#!/usr/bin/env bash
# Prints the i3 bars.conf for a bar state (barista|rs|off) from i3status-rust/i3/bars.conf.tmpl.
# Used by install.sh and barcycle.sh. Paths (BIN, CONFDIR) come from the env file install.sh writes;
# BARS_ENV overrides its location. The tray is always on bar-main (DP-0; primary HDMI-0 is disconnected).
set -euo pipefail
d=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=/dev/null
. "${BARS_ENV:-${XDG_CONFIG_HOME:-$HOME/.config}/custom_barista/bars.env}"
rsfont='font pango:PragmataPro Mono, Symbols Nerd Font Mono 18'
case ${1:-} in
  barista) m=dock;      f='# font: i3 default'; mc=$BIN; sc=$BIN ;;
  rs)      m=dock;      f=$rsfont; mc="i3status-rs $CONFDIR/config.toml"; sc="i3status-rs $CONFDIR/compact.toml" ;;
  off)     m=invisible; f='# font: i3 default'; mc=$BIN; sc=$BIN ;;
  *) echo "usage: $0 barista|rs|off" >&2; exit 2 ;;
esac
echo "# state: $1 (generated by barsconf.sh, rewritten by Win+i; edit i3status-rust/i3/bars.conf.tmpl instead)"
sed -e "s|@MODE@|$m|g" -e "s|@FONT@|$f|g" -e "s|@MAIN_CMD@|$mc|g" -e "s|@SMALL_CMD@|$sc|g" "$d/../i3/bars.conf.tmpl"
